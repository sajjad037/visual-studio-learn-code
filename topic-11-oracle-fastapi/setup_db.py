"""Step 6 — create the DevShelf table and insert three real rows, then read back."""
import os

import oracledb

WALLET_DIR = os.environ["ORACLE_WALLET_DIR"]
extra = {}
if os.environ.get("ORACLE_PROXY_HOST"):
    extra["https_proxy"] = os.environ["ORACLE_PROXY_HOST"]
    extra["https_proxy_port"] = int(os.environ.get("ORACLE_PROXY_PORT", "8899"))

ROWS = [
    ("python-oracledb documentation", "https://python-oracledb.readthedocs.io", "driver"),
    ("FastAPI documentation", "https://fastapi.tiangolo.com", "framework"),
    ("Autonomous Database documentation",
     "https://docs.oracle.com/en/cloud/paas/autonomous-database/", "database"),
]

with oracledb.connect(
    user=os.environ["ORACLE_USER"],
    password=os.environ["ORACLE_PASSWORD"],
    dsn=os.environ.get("ORACLE_DSN", "vsldb_tp"),
    config_dir=WALLET_DIR,
    wallet_location=WALLET_DIR,
    wallet_password=os.environ["ORACLE_WALLET_PASSWORD"],
    **extra,
) as connection:
    with connection.cursor() as cursor:
        try:
            cursor.execute("DROP TABLE shelf_items PURGE")
        except oracledb.Error:
            pass
        cursor.execute(
            """
            CREATE TABLE shelf_items (
                id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title      VARCHAR2(200) NOT NULL,
                url        VARCHAR2(400) NOT NULL,
                tag        VARCHAR2(40),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        cursor.executemany(
            "INSERT INTO shelf_items (title, url, tag) VALUES (:1, :2, :3)", ROWS
        )
        connection.commit()
        print(f"Inserted {len(ROWS)} rows. Reading them back:")
        for row in cursor.execute("SELECT id, title, url, tag FROM shelf_items ORDER BY id"):
            print(" ", row)
